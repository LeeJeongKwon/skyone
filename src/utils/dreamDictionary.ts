/**
 * Normalizes Korean search query by removing common filler suffixes:
 * e.g., "호랑이꿈" -> "호랑이", "똥을 밟았어요" -> "똥 밟", "돼지꿈을 꿨는데" -> "돼지"
 */
export function normalizeDreamQuery(query: string): string[] {
  if (!query) return [];

  const raw = query.trim().toLowerCase();
  // Remove punctuation
  const cleaned = raw.replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?'"~]/g, ' ');

  // Split into tokens
  const rawTokens = cleaned.split(/\s+/).filter(t => t.length > 0);

  const tokens: string[] = [];
  const stripSuffixes = [
    '꿈을꿨어요', '꿈을꿨는데', '꿈꿨어요', '꿈꿨는데', '꿈이', '꿈은', '꿈을', '꿈에', '꿈',
    '나오는', '나왔는데', '나왔어요', '나오는꿈',
    '보는', '봤는데', '봤어요', '보는꿈',
    '하는', '했는데', '했어요', '하는꿈',
    '잡는', '잡았는데', '잡았어요', '잡는꿈',
    '먹는', '먹었는데', '먹었어요', '먹는꿈',
    '타는', '탔는데', '탔어요', '타는꿈',
    '물리는', '물렸는데', '물렸어요',
    '빠지는', '빠졌는데', '빠졌어요',
    '잃어버린', '잃어버렸는데',
  ];

  rawTokens.forEach(token => {
    let t = token;
    for (const suffix of stripSuffixes) {
      if (t.length > suffix.length && t.endsWith(suffix)) {
        t = t.slice(0, t.length - suffix.length);
        break;
      }
    }
    if (t.length > 0) {
      tokens.push(t);
    }
  });

  return tokens.length > 0 ? tokens : [raw];
}

/**
 * Intelligent multi-tier search matching for dream dictionary
 */
export function searchDreamDictionary(
  query: string,
  category: string = 'all',
  grade: string = 'all'
): DreamEntry[] {
  let list = COMPREHENSIVE_DREAM_DICTIONARY;

  // Filter category
  if (category !== 'all') {
    list = list.filter(item => item.category === category);
  }

  // Filter grade
  if (grade !== 'all') {
    list = list.filter(item => item.type.includes(grade));
  }

  const trimmed = query.trim();
  if (!trimmed) {
    return list;
  }

  const tokens = normalizeDreamQuery(trimmed);

  return list.filter(item => {
    const fullSearchableText = [
      item.keyword,
      ...item.aliasKeywords,
      item.summary,
      item.desc,
      item.actionTip,
      item.category,
      item.type,
      item.fortuneField,
    ].join(' ').toLowerCase();

    // Direct substring check
    if (fullSearchableText.includes(trimmed.toLowerCase())) {
      return true;
    }

    // Token match: if ANY token matches
    return tokens.some(token => fullSearchableText.includes(token.toLowerCase()));
  });
}
